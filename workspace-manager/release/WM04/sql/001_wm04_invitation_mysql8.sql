-- WM04 schema; execute ONLY on sakai_framework_8082 after creating a backup.
-- Do not run against the original Sakai database.
CREATE TABLE IF NOT EXISTS SAKAI_BOOTSTRAP_INVITATION (
    INVITATION_ID CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    SITE_ID VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    INVITEE_USER_ID VARCHAR(99) NOT NULL,
    INVITED_BY VARCHAR(99) NOT NULL,
    ROLE_ID VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    TOKEN_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    STATUS VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    CREATED_AT BIGINT NOT NULL,
    EXPIRES_AT BIGINT NOT NULL,
    PRIMARY KEY (INVITATION_ID),
    UNIQUE KEY WM04_TOKEN_HASH_UNIQUE (TOKEN_HASH),
    KEY WM04_SITE_CREATED (SITE_ID, CREATED_AT),
    KEY WM04_INVITEE_STATUS (SITE_ID, INVITEE_USER_ID, STATUS, EXPIRES_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
